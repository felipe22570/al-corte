// Writes supabase/tests/120-installment-parity.test.sql from the shared fixture, so pgTAP checks the SQL
// installment plan against the same expected rows Vitest checks for buildInstallmentPlan (step 31).
// Usage: node scripts/generate-installment-parity-test.mjs
import { readFileSync, writeFileSync } from "node:fs";

export function parityTestSql(fixture) {
  return `-- Generated by scripts/generate-installment-parity-test.mjs from lib/domain/__tests__/fixtures/installment-parity.json. Do not edit.
begin;
select no_plan();
select set_config('test.fixture', $fixture$${JSON.stringify(fixture)}$fixture$, true);
with cases as (select value as c from jsonb_array_elements(current_setting('test.fixture')::jsonb)),
normalized as (
  select c->>'name' as name,
    (select jsonb_agg(jsonb_build_array((r->>'number')::int, r->>'cutoff_date', (r->>'principal')::numeric, (r->>'interest')::numeric, (r->>'total')::numeric,
      (r->>'balance_after')::numeric, (r->>'principal_cop')::numeric, (r->>'interest_cop')::numeric, (r->>'total_cop')::numeric) order by (r->>'number')::int)
     from jsonb_array_elements(private.build_installment_rows((c->>'amount')::numeric, (c->>'count')::int, (c->>'rateEa')::numeric, c->>'method',
       (c->>'interestFree')::boolean, c->>'interestMode', c->>'currency', (c->>'fxRate')::numeric, (c->>'cutoffDay')::int, (c->>'date')::date)) r) as actual,
    (select jsonb_agg(jsonb_build_array((r->>'number')::int, r->>'cutoffDate', (r->>'principal')::numeric, (r->>'interest')::numeric, (r->>'total')::numeric,
      (r->>'balanceAfter')::numeric, (r->>'principalCop')::numeric, (r->>'interestCop')::numeric, (r->>'totalCop')::numeric) order by (r->>'number')::int)
     from jsonb_array_elements(c->'rows') r) as expected
  from cases
)
select is(actual, expected, 'paridad SQL/TypeScript: ' || name) from normalized;
select throws_ok($$ select private.build_installment_rows(0.54, 36, 0, 'fixed_principal', false, 'per_installment', 'COP', null, 15, '2026-01-20') $$,
  '22023', 'El valor es muy pequeño para esa cantidad de cuotas.', 'rechaza un plan cuyo redondeo agota el capital');
select * from finish();
rollback;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const fixture = JSON.parse(readFileSync("lib/domain/__tests__/fixtures/installment-parity.json", "utf8"));
  writeFileSync("supabase/tests/120-installment-parity.test.sql", parityTestSql(fixture));
}
